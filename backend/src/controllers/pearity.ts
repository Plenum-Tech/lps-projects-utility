const DISABLED = { error: "The Pearity integration is turned off", code: "integration_disabled" };

/** GET /api/integrations/pearity/status */
export async function pearityStatus(_req: Request, res: Response): Promise<void> {
  const settings = await pearitySettings();
  res.json({ enabled: pearityActive(settings) });
}

/** "Generated by": one row per user (latest first) with their count. */
async function generatedBy(taskId: mongoose.Types.ObjectId) {
  const rows = await PearityTagUsage.aggregate<{
    _id: mongoose.Types.ObjectId;
    count: number;
    lastAt: Date;
    sources: string[];
  }>([
    { $match: { task: taskId } },
    { $group: { _id: "$user", count: { $sum: 1 }, lastAt: { $max: "$at" }, sources: { $addToSet: "$source" } } },
    { $sort: { lastAt: -1 } },
    { $limit: 50 },
  ]);
  const users = rows.length ? await User.find({ _id: { $in: rows.map((r) => r._id) } }).select("name").lean() : [];
  const nameById = new Map(users.map((u) => [u._id.toString(), u.name]));
  return rows.map((row) => ({
    user: { _id: row._id.toString(), name: nameById.get(row._id.toString()) ?? "Former user" },
    count: row.count,
    lastAt: row.lastAt,
    sources: row.sources,
  }));
}

/** Aggregate journey counts + recent outcome / DAM links for the task detail trail. */
async function pearityTrail(taskId: mongoose.Types.ObjectId) {
  const [historyCounts, assets] = await Promise.all([
    TaskHistory.aggregate<{ _id: string; count: number }>([
      {
        $match: {
          task: taskId,
          action: {
            $in: [
              "pearity_generated",
              "pearity_job_started",
              "pearity_job_completed",
              "pearity_job_failed",
              "pearity_saved_to_dam",
            ],
          },
        },
      },
      { $group: { _id: "$action", count: { $sum: 1 } } },
    ]),
    PearityTaskAsset.find({ task: taskId })
      .sort({ createdAt: -1 })
      .limit(40)
      .select("url title mimeType damAssetId damFolderPath tagNo jobId pearityUrl createdAt")
      .lean(),
  ]);
  const byAction = Object.fromEntries(historyCounts.map((r) => [r._id, r.count])) as Record<string, number>;
  const jobsStarted = byAction.pearity_job_started ?? 0;
  const jobsCompleted = byAction.pearity_job_completed ?? 0;
  const jobsFailed = byAction.pearity_job_failed ?? 0;
  const savedToDam = byAction.pearity_saved_to_dam ?? 0;
  const generateClicks = byAction.pearity_generated ?? 0;
  return {
    generateClicks,
    jobsStarted,
    jobsCompleted,
    jobsFailed,
    savedToDam,
    outcomes: assets.map((a) => ({
      _id: a._id.toString(),
      url: a.url,
      title: a.title ?? null,
      mimeType: a.mimeType ?? null,
      damAssetId: a.damAssetId ?? null,
      damFolderPath: a.damFolderPath ?? null,
      tagNo: a.tagNo ?? null,
      jobId: a.jobId ?? null,
      pearityUrl: a.pearityUrl ?? null,
      createdAt: a.createdAt,
    })),
  };
}

/**
 * GET /api/tasks/:id/pearity — any signed-in user; read-only viewers get no
 * engine link (neither `generateUrl` nor a `tagUrl` that falls back to it).
 */
export async function getTaskPearity(req: Request, res: Response): Promise<void> {
  const task = await getReadableTaskOr404(req, res);
  if (!task) return;
  const settings = await pearitySettings();
  const taskId = task._id as mongoose.Types.ObjectId;
  const canGenerate = await canViewTaskAsync(req.user!, task);
  const [tag, contexts, trail] = await Promise.all([
    PearityTag.findOne({ task: taskId }),
    taskContexts([task]),
    pearityTrail(taskId),
  ]);
  const context = contexts.get(taskId.toString())!;
  const fullRef = tag ? (await tagRefs([tag], { contexts })).get(taskId.toString()) ?? null : null;
  const ref = canGenerate ? fullRef : readOnlyTagRef(settings, fullRef);
  const usageCount = tag?.usageCount ?? 0;
  res.json({
    enabled: pearityActive(settings),
    tag: ref,
    tagUrl: ref?.tagUrl ?? null,
    proposedTagName: tag ? tag.tagName : context.fields.taskTag || buildTagName(context),
    generateUrl: tag && canGenerate ? pearityGenerateUrl(settings, tag, taskId, context) : null,
    usageCount,
    /** Alias for clients that prefer a clearer name than usageCount. */
    generationsCount: usageCount,
    /** Times someone used Generate on Pearity for this task (history). */
    tasksGeneratedOnPearity: trail.generateClicks,
    jobsCompleted: trail.jobsCompleted,
    jobsStarted: trail.jobsStarted,
    jobsFailed: trail.jobsFailed,
    savedToDam: trail.savedToDam,
    outcomes: trail.outcomes,
    generatedBy: tag ? await generatedBy(taskId) : [],
  });
}

/** POST /api/tasks/:id/pearity/generate — any viewer: { created, tag, generateUrl }. */
export async function generateTaskPearity(req: Request, res: Response): Promise<void> {
  const settings = await pearitySettings();
  if (!pearityActive(settings)) {
    res.status(503).json(DISABLED);
    return;
  }
  const task = await getViewableTaskOr404(req, res);
  if (!task) return;
  const user = req.user!;
  const taskId = task._id as mongoose.Types.ObjectId;
  const context = (await taskContexts([task])).get(taskId.toString())!;
  const { tag, created } = await ensurePearityTag(task, context, user._id as mongoose.Types.ObjectId, "utility");
  await recordPearityUsage(tag, user._id as mongoose.Types.ObjectId, "utility");
  recordTaskHistory(taskId, user, "pearity_generated", {
    tagId: tag.tagId,
    tagName: tag.tagName,
    created,
    source: "utility",
  });
  if (created) {
    logActivity({
      action: "pearity_tag_created",
      actor: user,
      targetType: "Task",
      targetId: taskId,
      targetName: task.title,
      details: { tagId: tag.tagId, tagName: tag.tagName, source: "utility" },
      ip: req.ip,
    });
  }
  const ref = (await tagRefs([tag], { contexts: new Map([[taskId.toString(), context]]) })).get(taskId.toString())!;
  res.status(created ? 201 : 200).json({
    created,
    tag: ref,
    tagUrl: ref.tagUrl,
    generateUrl: pearityGenerateUrl(settings, tag, taskId, context),
  });
}

