async function settingsJson() {
  const settings = await pearitySettings();
  return {
    settings: {
      enabled: settings.enabled,
      engineUrlTemplate: settings.engineUrlTemplate,
      tagUrlTemplate: settings.tagUrlTemplate,
      allowedIps: settings.allowedIps,
      updatedAt: settings.updatedAt,
    },
    placeholders: PEARITY_PLACEHOLDERS,
    apiBasePath: "/api/integrations/pearity/v1",
  };
}

/** GET /api/integrations/pearity/settings */
export async function getPearitySettings(_req: Request, res: Response): Promise<void> {
  res.json(await settingsJson());
}

function fieldError(res: Response, field: string, error: string): void {
  res.status(400).json({ error, field });
}

/** PATCH /api/integrations/pearity/settings — { enabled?, engineUrlTemplate?, allowedIps? } */
export async function updatePearitySettings(req: Request, res: Response): Promise<void> {
  const body = (req.body ?? {}) as Record<string, unknown>;
  const current = await IntegrationSettings.findOne({ key: "pearity" });
  const update: Record<string, unknown> = {};

  if (body.enabled !== undefined) {
    if (typeof body.enabled !== "boolean") return fieldError(res, "enabled", "enabled must be true or false");
    update.enabled = body.enabled;
  }
  if (body.engineUrlTemplate !== undefined) {
    if (typeof body.engineUrlTemplate !== "string") {
      return fieldError(res, "engineUrlTemplate", "engineUrlTemplate must be a string");
    }
    const template = body.engineUrlTemplate.trim();
    const problem = template ? templateError(template) : null;
    if (problem) return fieldError(res, "engineUrlTemplate", problem);
    update.engineUrlTemplate = template;
  }
  if (body.tagUrlTemplate !== undefined) {
    if (typeof body.tagUrlTemplate !== "string") {
      return fieldError(res, "tagUrlTemplate", "tagUrlTemplate must be a string");
    }
    const template = body.tagUrlTemplate.trim();
    const problem = template ? templateError(template) : null;
    if (problem) {
      return fieldError(res, "tagUrlTemplate", problem.replace("production engine URL template", "tag link URL"));
    }
    update.tagUrlTemplate = template;
  }
  if (body.allowedIps !== undefined) {
    if (!Array.isArray(body.allowedIps) || body.allowedIps.some((ip) => typeof ip !== "string")) {
      return fieldError(res, "allowedIps", "allowedIps must be a list of IP addresses");
    }
    const ips = [...new Set((body.allowedIps as string[]).map((ip) => ip.trim()).filter(Boolean))];
    if (ips.length > INTEGRATION_LIMITS.allowedIpsMax) {
      return fieldError(res, "allowedIps", `At most ${INTEGRATION_LIMITS.allowedIpsMax} entries`);
    }
    const bad = ips.find((ip) => ip.length > INTEGRATION_LIMITS.allowedIpMax || !isValidIpEntry(ip));
    if (bad) return fieldError(res, "allowedIps", `"${bad}" is not a valid IP address or CIDR range`);
    update.allowedIps = ips;
  }
  if (Object.keys(update).length === 0) {
    res.status(400).json({ error: "Nothing to update" });
    return;
  }

  const enabled = (update.enabled as boolean | undefined) ?? current?.enabled ?? false;
  const template = (update.engineUrlTemplate as string | undefined) ?? current?.engineUrlTemplate ?? "";
  if (enabled && !template) {
    return fieldError(res, "engineUrlTemplate", "Set the production engine URL template before turning the integration on.");
  }

  await IntegrationSettings.findOneAndUpdate(
    { key: "pearity" },
    { $set: { ...update, updatedBy: req.user!._id }, $setOnInsert: { key: "pearity" } },
    { upsert: true, runValidators: true }
  );
  invalidatePearitySettings();
  logActivity({
    action: "pearity_settings_updated",
    actor: req.user,
    targetType: "IntegrationSettings",
    targetName: "Pearity",
    details: { fields: Object.keys(update), enabled },
    ip: req.ip,
  });
  res.json(await settingsJson());
}

