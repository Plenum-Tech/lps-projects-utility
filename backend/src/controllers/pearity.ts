type KeyRow = {
  _id: mongoose.Types.ObjectId;
  name: string;
  prefix: string;
  scopes: string[];
  lastUsedAt: Date | null;
  createdAt: Date;
  revokedAt: Date | null;
  createdBy?: { _id: mongoose.Types.ObjectId; name?: string } | mongoose.Types.ObjectId | null;
};

function keyJson(key: KeyRow) {
  const createdBy =
    key.createdBy && typeof key.createdBy === "object" && "name" in key.createdBy
      ? { _id: key.createdBy._id.toString(), name: key.createdBy.name ?? "" }
      : null;
  return {
    _id: key._id.toString(),
    name: key.name,
    prefix: key.prefix,
    scopes: key.scopes,
    lastUsedAt: key.lastUsedAt ?? null,
    createdAt: key.createdAt,
    createdBy,
    revokedAt: key.revokedAt ?? null,
  };
}

/** GET /api/integrations/pearity/keys */
export async function listPearityKeys(_req: Request, res: Response): Promise<void> {
  const keys = await ApiKey.find({ integration: "pearity" })
    .sort({ revokedAt: 1, createdAt: -1 })
    .limit(200)
    .populate("createdBy", "name")
    .lean<KeyRow[]>();
  res.json({ keys: keys.map(keyJson) });
}

/** POST /api/integrations/pearity/keys — { name, scopes } → { key (shown once), apiKey }. */
export async function createPearityKey(req: Request, res: Response): Promise<void> {
  const body = (req.body ?? {}) as Record<string, unknown>;
  const name = typeof body.name === "string" ? body.name.trim() : "";
  if (!name || name.length > 80) return fieldError(res, "name", "Give the key a name (1–80 characters).");
  const rawScopes = body.scopes === undefined ? [...API_KEY_SCOPES] : body.scopes;
  if (
    !Array.isArray(rawScopes) ||
    rawScopes.length === 0 ||
    rawScopes.some((s) => !(API_KEY_SCOPES as readonly unknown[]).includes(s))
  ) {
    return fieldError(res, "scopes", `scopes must be a non-empty list of: ${API_KEY_SCOPES.join(", ")}`);
  }
  const scopes = [...new Set(rawScopes as ApiKeyScope[])];
  const activeCount = await ApiKey.countDocuments({ integration: "pearity", revokedAt: null });
  if (activeCount >= 20) {
    res.status(409).json({ error: "At most 20 active keys. Revoke one you no longer use first." });
    return;
  }

  const generated = generateApiKey();
  const doc = await ApiKey.create({
    integration: "pearity",
    name,
    prefix: generated.prefix,
    hash: generated.hash,
    scopes,
    createdBy: req.user!._id,
  });
  logActivity({
    action: "pearity_key_created",
    actor: req.user,
    targetType: "ApiKey",
    targetId: doc._id as mongoose.Types.ObjectId,
    targetName: name,
    details: { prefix: generated.prefix, scopes },
    ip: req.ip,
  });
  res.setHeader("Cache-Control", "no-store");
  res.status(201).json({
    key: generated.key,
    apiKey: keyJson({
      ...(doc.toObject() as unknown as KeyRow),
      createdBy: { _id: req.user!._id as mongoose.Types.ObjectId, name: req.user!.name },
    }),
  });
}

/** POST /api/integrations/pearity/keys/:keyId/revoke */
export async function revokePearityKey(req: Request, res: Response): Promise<void> {
  const keyId = param(req, "keyId");
  if (!keyId || !mongoose.isValidObjectId(keyId)) {
    res.status(404).json({ error: "API key not found" });
    return;
  }
  const doc = await ApiKey.findOne({ _id: keyId, integration: "pearity" });
  if (!doc) {
    res.status(404).json({ error: "API key not found" });
    return;
  }
  if (!doc.revokedAt) {
    doc.revokedAt = new Date();
    doc.revokedBy = req.user!._id as mongoose.Types.ObjectId;
    await doc.save();
    logActivity({
      action: "pearity_key_revoked",
      actor: req.user,
      targetType: "ApiKey",
      targetId: doc._id as mongoose.Types.ObjectId,
      targetName: doc.name,
      details: { prefix: doc.prefix },
      ip: req.ip,
    });
  }
  const populated = await ApiKey.findById(doc._id).populate("createdBy", "name").lean<KeyRow>();
  res.json({ apiKey: keyJson(populated!) });
}

/**
 * POST /api/projects/:id/pearity/generate — anyone who can view the project:
 * makes sure it has its tag, freezes the tag (first time), and returns the
 * production-engine URL filled with the project's details.
 */
export async function generateProjectPearity(req: Request, res: Response): Promise<void> {
  const settings = await pearitySettings();
  if (!pearityActive(settings)) {
    res.status(503).json(DISABLED);
    return;
  }
  const id = req.params.id;
  if (typeof id !== "string" || !mongoose.isValidObjectId(id)) {
    res.status(400).json({ error: "Invalid project ID" });
    return;
  }
  const project = await Project.findById(id);
  if (!project || !canViewProject(req.user!, project)) {
    res.status(404).json({ error: "Project not found" });
    return;
  }
  const user = req.user!;
  const tag = project.tag || (await ensureProjectTag(project._id as mongoose.Types.ObjectId));
  if (!tag) {
    res.status(500).json({ error: "Could not create the project tag" });
    return;
  }
  const created = !project.pearityGeneratedAt;
  if (created) {
    await Project.updateOne(
      { _id: project._id, pearityGeneratedAt: null },
      { $set: { pearityGeneratedAt: new Date(), pearityGeneratedBy: user._id } }
    );
    logActivity({
      action: "pearity_tag_created",
      actor: user,
      targetType: "project",
      targetId: project._id as mongoose.Types.ObjectId,
      targetName: `${project.code} · ${project.name}`,
      details: { projectTag: tag, source: "utility" },
      ip: req.ip,
    });
  }
  const brandId = project.naming?.brand ?? project.brand ?? null;
  const brand = brandId ? await Brand.findById(brandId).select("name").lean() : null;
  res.status(created ? 201 : 200).json({
    created,
    tag,
    generateUrl: pearityProjectUrl(settings, {
      id: project._id.toString(),
      name: project.name,
      code: project.code,
      tag,
      brand: brand?.name ?? "",
      month: projectMonth(project) ?? "",
      type: project.naming?.type ?? "",
      title: project.naming?.title ?? project.name,
      startDate: project.startDate ?? null,
      deadline: project.deadline ?? null,
    }),
  });
}
