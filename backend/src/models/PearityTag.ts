import mongoose, { Schema } from "mongoose";

// ---------------------------------------------------------------------------
// Pearity tag — exactly one per task for the whole organisation (unique index
// on `task`). `tagId` / `tagName` never change once created, so Pearity's side
// stays stable when the task, its project brand or its category is renamed.
// Usage (who generated content against the tag) is one-to-many: PearityTagUsage.
// ---------------------------------------------------------------------------

export const PEARITY_USAGE_SOURCES = ["utility", "pearity"] as const;
export type PearityUsageSource = (typeof PEARITY_USAGE_SOURCES)[number];

export interface IPearityTag extends mongoose.Document {
  task: mongoose.Types.ObjectId;
  /** "pt_" + 8 random [0-9a-z] characters — stable, URL-safe. */
  tagId: string;
  /** Brand_Category_TaskCode, sanitized (see lib/pearity.ts). Immutable. */
  tagName: string;
  /** Task code at creation ("GENAI-65" / "Task-12"). */
  taskCodeSnapshot: string;
  brandSnapshot: { id: mongoose.Types.ObjectId | null; name: string };
  categorySnapshot: { id: mongoose.Types.ObjectId | null; name: string };
  createdBy: mongoose.Types.ObjectId | null;
  /** Where the first Generate came from. */
  createdVia: PearityUsageSource;
  usageCount: number;
  lastUsedAt: Date | null;
  createdAt: Date;
  updatedAt: Date;
}

const snapshotSchema = new Schema(
  {
    id: { type: Schema.Types.ObjectId, default: null },
    name: { type: String, trim: true, maxlength: 120, default: "" },
  },
  { _id: false }
);

const pearityTagSchema = new Schema<IPearityTag>(
  {
    task: { type: Schema.Types.ObjectId, ref: "Task", required: true },
    tagId: { type: String, required: true, match: /^pt_[0-9a-z]{8}$/ },
    tagName: { type: String, required: true, trim: true, maxlength: 200 },
    taskCodeSnapshot: { type: String, trim: true, maxlength: 60, default: "" },
    brandSnapshot: { type: snapshotSchema, default: () => ({}) },
    categorySnapshot: { type: snapshotSchema, default: () => ({}) },
    createdBy: { type: Schema.Types.ObjectId, ref: "User", default: null },
    createdVia: { type: String, enum: PEARITY_USAGE_SOURCES, default: "utility" },
    usageCount: { type: Number, default: 0, min: 0 },
    lastUsedAt: { type: Date, default: null },
  },
  { timestamps: true }
);

// One tag per task — the atomic guard for concurrent Generate clicks.
pearityTagSchema.index({ task: 1 }, { unique: true, name: "task_unique" });
pearityTagSchema.index({ tagId: 1 }, { unique: true, name: "tagId_unique" });
pearityTagSchema.index({ tagName: 1 });
// Bulk sync (GET /tags?updatedSince=) — cursor on (updatedAt, _id).
pearityTagSchema.index({ updatedAt: 1, _id: 1 });

pearityTagSchema.set("toJSON", {
  transform: (_doc, ret) => {
    const json = ret as unknown as Record<string, unknown>;
    delete json.__v;
    return json;
  },
});

export const PearityTag = mongoose.model<IPearityTag>("PearityTag", pearityTagSchema);

export interface IPearityTagUsage extends mongoose.Document {
  tag: mongoose.Types.ObjectId;
  task: mongoose.Types.ObjectId;
  user: mongoose.Types.ObjectId;
  source: PearityUsageSource;
  at: Date;
}

const pearityTagUsageSchema = new Schema<IPearityTagUsage>({
  tag: { type: Schema.Types.ObjectId, ref: "PearityTag", required: true },
  task: { type: Schema.Types.ObjectId, ref: "Task", required: true },
  user: { type: Schema.Types.ObjectId, ref: "User", required: true },
  source: { type: String, enum: PEARITY_USAGE_SOURCES, required: true },
  at: { type: Date, default: () => new Date() },
});

// "Generated by" list on the task detail — newest first.
pearityTagUsageSchema.index({ task: 1, at: -1 });
pearityTagUsageSchema.index({ tag: 1, at: -1 });

pearityTagUsageSchema.set("toJSON", {
  transform: (_doc, ret) => {
    const json = ret as unknown as Record<string, unknown>;
    delete json.__v;
    return json;
  },
});

export const PearityTagUsage = mongoose.model<IPearityTagUsage>("PearityTagUsage", pearityTagUsageSchema);
