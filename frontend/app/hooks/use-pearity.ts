import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";

import { SettingsFieldError } from "@/hooks/use-settings";
import { useToast } from "@/hooks/use-toast";
import { taskKeys } from "@/hooks/use-tasks";
import { api, getErrorMessage } from "@/lib/api";
import type {
  PearityApiKey,
  PearityApiScope,
  PearityGenerateResponse,
  PearityKeyCreateResponse,
  PearitySettings,
  PearitySettingsResponse,
  TaskPearityInfo,
} from "@/types";

export const pearityKeys = {
  status: ["pearity", "status"] as const,
  settings: ["pearity", "settings"] as const,
  apiKeys: ["pearity", "keys"] as const,
  task: (id: string) => ["pearity", "task", id] as const,
};

/** Is the Pearity integration on (Generate button / tag column shown)? */
export function usePearityStatus(enabled = true) {
  return useQuery({
    queryKey: pearityKeys.status,
    queryFn: async () => {
      const { data } = await api.get<{ enabled: boolean }>("/integrations/pearity/status");
      return data.enabled;
    },
    staleTime: 60_000,
    enabled,
  });
}

/** A task's tag, proposed tag name and "Generated by" list. */
export function useTaskPearity(taskId: string | null, enabled = true) {
  return useQuery({
    queryKey: pearityKeys.task(taskId ?? ""),
    queryFn: async () => {
      const { data } = await api.get<TaskPearityInfo>(`/tasks/${taskId}/pearity`);
      return data;
    },
    enabled: Boolean(taskId) && enabled,
  });
}

/**
 * Opens a blank tab during the click (so popup blockers allow it), then points
 * it at the engine URL once the server answers. Returns a function that loads
 * the URL, or closes the tab on failure.
 */
function openPendingTab(): (url: string | null) => void {
  const tab = typeof window !== "undefined" ? window.open("about:blank", "_blank") : null;
  return (url) => {
    if (!tab) {
      if (url) window.open(url, "_blank", "noopener,noreferrer");
      return;
    }
    if (!url) {
      tab.close();
      return;
    }
    try {
      tab.opener = null;
    } catch {
      // Cross-origin already: nothing to detach.
    }
    tab.location.href = url;
  };
}

/** Generate: create (first time) or reuse the task's tag, record usage, open the engine. */
export function usePearityGenerate() {
  const queryClient = useQueryClient();
  const toast = useToast();
  return useMutation({
    mutationFn: async ({ taskId }: { taskId: string; navigate: (url: string | null) => void }) => {
      const { data } = await api.post<PearityGenerateResponse>(`/tasks/${taskId}/pearity/generate`);
      return data;
    },
    onSuccess: (data, { taskId, navigate }) => {
      navigate(data.generateUrl);
      if (data.created) toast.success(`Created Pearity tag ${data.tag.tagNo ? `#${data.tag.tagNo} · ` : ""}${data.tag.tagName}`);
      else toast.info(`Using existing tag ${data.tag.tagNo ? `#${data.tag.tagNo} · ` : ""}${data.tag.tagName}`);
      void queryClient.invalidateQueries({ queryKey: pearityKeys.task(taskId) });
      void queryClient.invalidateQueries({ queryKey: taskKeys.historyAll(taskId) });
      if (data.created) {
        void queryClient.invalidateQueries({ queryKey: taskKeys.detail(taskId) });
        void queryClient.invalidateQueries({ queryKey: taskKeys.lists });
      }
    },
    onError: (error, { navigate }) => {
      navigate(null);
      toast.error(getErrorMessage(error));
    },
  });
}

/** Starts a Generate inside the click handler (opens the pending tab synchronously). */
export function startPearityGenerate(
  generate: ReturnType<typeof usePearityGenerate>,
  taskId: string
): void {
  const navigate = openPendingTab();
  generate.mutate({ taskId, navigate });
}

// --- Admin: settings + keys ------------------------------------------------------

function toFieldError(error: unknown): SettingsFieldError {
  const field = (error as { response?: { data?: { field?: unknown } } })?.response?.data?.field ?? null;
  return new SettingsFieldError(getErrorMessage(error), typeof field === "string" ? field : null);
}

export function usePearitySettings() {
  return useQuery({
    queryKey: pearityKeys.settings,
    queryFn: async () => {
      const { data } = await api.get<PearitySettingsResponse>("/integrations/pearity/settings");
      return data;
    },
  });
}

export function useUpdatePearitySettings() {
  const queryClient = useQueryClient();
  const toast = useToast();
  return useMutation({
    mutationFn: async (input: Partial<Pick<PearitySettings, "enabled" | "engineUrlTemplate" | "tagUrlTemplate" | "allowedIps">>) => {
      try {
        const { data } = await api.patch<PearitySettingsResponse>("/integrations/pearity/settings", input);
        return data;
      } catch (error) {
        throw toFieldError(error);
      }
    },
    onSuccess: (data) => {
      queryClient.setQueryData(pearityKeys.settings, data);
      void queryClient.invalidateQueries({ queryKey: pearityKeys.status });
      toast.success("Pearity settings saved");
    },
    onError: (error) => toast.error(getErrorMessage(error)),
  });
}

export function usePearityApiKeys() {
  return useQuery({
    queryKey: pearityKeys.apiKeys,
    queryFn: async () => {
      const { data } = await api.get<{ keys: PearityApiKey[] }>("/integrations/pearity/keys");
      return data.keys;
    },
  });
}

export function useCreatePearityKey() {
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: async (input: { name: string; scopes: PearityApiScope[] }) => {
      const { data } = await api.post<PearityKeyCreateResponse>("/integrations/pearity/keys", input);
      return data;
    },
    onSuccess: () => void queryClient.invalidateQueries({ queryKey: pearityKeys.apiKeys }),
  });
}

export function useRevokePearityKey() {
  const queryClient = useQueryClient();
  const toast = useToast();
  return useMutation({
    mutationFn: async (id: string) => {
      const { data } = await api.post<{ apiKey: PearityApiKey }>(`/integrations/pearity/keys/${id}/revoke`);
      return data.apiKey;
    },
    onSuccess: (key) => {
      toast.success(`Revoked ${key.name}`);
      void queryClient.invalidateQueries({ queryKey: pearityKeys.apiKeys });
    },
    onError: (error) => toast.error(getErrorMessage(error)),
  });
}

/** Client-side mirror of the server's template fill (for the settings preview). */
export function fillPearityTemplate(template: string, values: Record<string, string>): string {
  return template.replace(/\{([A-Za-z]+)\}/g, (whole, name: string) =>
    name in values ? encodeURIComponent(values[name] ?? "") : whole
  );
}
