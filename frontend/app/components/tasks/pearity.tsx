export const PEARITY_OFF_MESSAGE =
  "Pearity isn't switched on yet. An admin turns it on in Settings → Integrations → Pearity (with the Production Engine URL).";

// ---------------------------------------------------------------------------
// Pearity tag UI: the Generate action (detail header + table ⋮ menu), the tag
// chip with copy / open, and the "Generated by" list.
// ---------------------------------------------------------------------------

/**
 * Generate flow for one task. With a tag: opens the engine at once (the server
 * records usage). Without: a confirm naming the tag that will be created first.
 */
export function usePearityGenerateAction(task: Pick<Task, "_id" | "pearityTag">) {
  const status = usePearityStatus();
  const generate = usePearityGenerate();
  const [confirming, setConfirming] = useState(false);
  const info = useTaskPearity(task._id, confirming);
  // The list row may be stale: trust the detail lookup once it has loaded.
  const hasTag = Boolean(task.pearityTag) || Boolean(info.data?.tag);

  function run() {
    startPearityGenerate(generate, task._id);
  }

  function onSelect() {
    if (hasTag) run();
    else setConfirming(true);
  }

  const dialog = (
    <ConfirmDialog
      open={confirming}
      onOpenChange={setConfirming}
      title="Create the Pearity tag?"
      description={
        info.isPending ? (
          <span className="inline-flex items-center gap-2">
            <LuLoaderCircle aria-hidden className="size-3.5 animate-spin" />
            Preparing the tag name…
          </span>
        ) : info.data?.tag ? (
          <>
            This task already has the tag <TagName name={info.data.tag.tagName} />. Generate opens the production
            engine with it.
          </>
        ) : (
          <>
            This creates the Pearity tag <TagName name={info.data?.proposedTagName ?? "…"} /> for this task. Everyone
            who generates for this task reuses the same tag, and its name never changes.
          </>
        )
      }
      confirmLabel={info.data?.tag ? "Open engine" : "Create tag & open"}
      icon={<LuSparkles aria-hidden />}
      pending={generate.isPending}
      onConfirm={() => {
        if (info.isPending) return;
        run();
        setConfirming(false);
      }}
    />
  );

  return {
    visible: status.data === true,
    pending: generate.isPending,
    onSelect,
    dialog,
  };
}

function TagName({ name }: { name: string }) {
  return <code className="rounded bg-muted px-1.5 py-0.5 font-mono text-[0.8em] break-all text-foreground">{name}</code>;
}

/** "Generate" button for the task detail header (hidden while the integration is off). */
export function PearityGenerateButton({ task }: { task: Pick<Task, "_id" | "pearityTag"> }) {
  const action = usePearityGenerateAction(task);
  const toast = useToast();
  return (
    <>
      <Button
        size="sm"
        variant="outline"
        onClick={() => (action.visible ? action.onSelect() : toast.info(PEARITY_OFF_MESSAGE))}
        disabled={action.pending}
      >
        {action.pending ? <LuLoaderCircle aria-hidden className="animate-spin" /> : <LuSparkles aria-hidden />}
        Generate on Pearity
      </Button>
      {action.dialog}
    </>
  );
}

/** "Tag #12 · Ajmal_Design_GenAIHub-65" — "Tag #12" part omitted until numbered. */
export function pearityTagLabel(tag: Pick<PearityTagRef, "tagNo" | "tagName">): string {
  return tag.tagNo ? `Tag #${tag.tagNo} · ${tag.tagName}` : tag.tagName;
}

/** The tag label, linked into Pearity (new tab) when a tag URL is available. */
function PearityTagLink({ tag, className }: { tag: PearityTagRef; className?: string }) {
  const label = pearityTagLabel(tag);
  if (!tag.tagUrl) {
    return (
      <span className={cn("truncate font-mono text-xs", className)} title={label}>
        {label}
      </span>
    );
  }
  return (
    <a
      href={tag.tagUrl}
      target="_blank"
      rel="noopener noreferrer"
      aria-label={`Open tag ${tag.tagName} in Pearity`}
      title={`${label} — open in Pearity`}
      onClick={(event) => event.stopPropagation()}
      className={cn(
        "truncate rounded-sm font-mono text-xs text-primary underline-offset-2 outline-none hover:underline focus-visible:ring-2 focus-visible:ring-ring",
        className
      )}
    >
      {label}
    </a>
  );
}

/** Copy-to-clipboard icon button for a tag name. */
function CopyTagButton({ value }: { value: string }) {
  const toast = useToast();
  const [copied, setCopied] = useState(false);
  return (
    <Button
      type="button"
      variant="ghost"
      size="icon-xs"
      aria-label={`Copy tag ${value}`}
      title="Copy tag"
      onClick={async () => {
        if (await writeClipboard(value)) {
          setCopied(true);
          window.setTimeout(() => setCopied(false), 1500);
        } else toast.error("Couldn't copy — your browser blocked clipboard access.");
      }}
    >
      {copied ? <LuCheck aria-hidden /> : <LuCopy aria-hidden />}
    </Button>
  );
}

/** Task detail: Pearity tag chip (copy / open in the engine) + "Generated by". */
export function PearityTagSection({ task }: { task: Pick<Task, "_id" | "pearityTag"> }) {
  const status = usePearityStatus();
  const info = useTaskPearity(task._id, status.data === true);
  if (status.data !== true) return null;

  const tag = info.data?.tag ?? task.pearityTag ?? null;
  return (
    <section aria-labelledby="pearity-heading" className="space-y-2.5 rounded-lg border bg-muted/20 p-3">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <h3 id="pearity-heading" className="text-xs font-medium tracking-wide text-muted-foreground uppercase">
          Pearity tag
        </h3>
        {info.data && info.data.usageCount > 0 && (
          <span className="text-xs text-muted-foreground tabular-nums">
            {info.data.usageCount} {info.data.usageCount === 1 ? "generation" : "generations"}
          </span>
        )}
      </div>
      {tag ? (
        <div className="flex flex-wrap items-center gap-2">
          <span className="inline-flex max-w-full items-center gap-1 rounded-full border bg-background py-0.5 pr-1 pl-2.5">
            <LuTag aria-hidden className="size-3.5 shrink-0 text-primary" />
            <PearityTagLink tag={{ ...tag, tagUrl: info.data?.tagUrl ?? tag.tagUrl ?? null }} className="font-medium" />
            <CopyTagButton value={tag.tagName} />
            {info.data?.generateUrl && (
              <a
                href={info.data.generateUrl}
                target="_blank"
                rel="noopener noreferrer"
                aria-label={`Open ${tag.tagName} in the Pearity production engine`}
                title="Open in Pearity"
                className="inline-flex size-6 items-center justify-center rounded-md text-muted-foreground outline-none hover:bg-muted hover:text-foreground focus-visible:ring-2 focus-visible:ring-ring"
              >
                <LuExternalLink aria-hidden className="size-3.5" />
              </a>
            )}
          </span>
          <span className="text-xs text-muted-foreground">
            Created {formatDistanceToNow(new Date(tag.createdAt), { addSuffix: true })}
            {tag.createdBy && ` by ${tag.createdBy.name}`}
          </span>
        </div>
      ) : (
        <p className="text-sm text-muted-foreground">
          Not generated yet. The first <span className="font-medium text-foreground">Generate on Pearity</span> sends the task tag to Pearity.
        </p>
      )}

      {info.isPending && tag ? (
        <Skeleton className="h-7 w-48" />
      ) : info.data && info.data.generatedBy.length > 0 ? (
        <div className="space-y-1.5">
          <p className="text-xs text-muted-foreground">Generated by</p>
          <ul className="flex flex-wrap gap-2">
            {info.data.generatedBy.map((row) => (
              <li
                key={row.user._id}
                className="flex items-center gap-1.5 rounded-full border bg-background py-0.5 pr-2.5 pl-0.5"
                title={`Last ${formatDateTime(row.lastAt)}${row.sources.includes("pearity") ? " · also from Pearity" : ""}`}
              >
                <UserAvatar user={row.user} />
                <span className="text-xs font-medium">{row.user.name}</span>
                <span className="text-xs text-muted-foreground">
                  {formatDistanceToNow(new Date(row.lastAt), { addSuffix: true })}
                  {row.count > 1 && ` · ${row.count}×`}
                </span>
              </li>
            ))}
          </ul>
        </div>
      ) : null}
    </section>
  );
}

/** Tasks table cell: "Tag #12 · name" linked into Pearity (copyable) or "—". */
export function PearityTagCell({ task, className }: { task: Pick<Task, "pearityTag" | "tag">; className?: string }) {
  if (!task.pearityTag) {
    return task.tag ? (
      <span className="font-mono text-xs text-muted-foreground" title="Task tag — not generated on Pearity yet">
        {task.tag}
      </span>
    ) : (
      <span className="text-muted-foreground">--</span>
    );
  }
  return (
    <span className={cn("inline-flex max-w-72 items-center gap-0.5", className)}>
      <PearityTagLink tag={task.pearityTag} />
      <CopyTagButton value={task.pearityTag.tagName} />
    </span>
  );
}
