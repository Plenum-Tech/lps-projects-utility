// Writes the OpenUI component prompt of the Leadership Insights library to the
// backend (it can't import the frontend). Run after changing
// app/lib/insights/schema.ts:  bun run insights:prompt
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { buildInsightsLibrary, PROMPT_EXAMPLES, PROMPT_RULES, type InsightComponentName } from "../app/lib/insights/schema";

process.env.OPENUI_TELEMETRY_DISABLED = "1";

const stub = () => null;
const names: InsightComponentName[] = [
  "Report", "Card", "StatRow", "Stat", "Table", "BarChart", "StackedBar", "LineChart",
  "PieChart", "Series", "Slice", "List", "Callout", "Text", "FollowUps",
];
const library = buildInsightsLibrary(Object.fromEntries(names.map((n) => [n, stub])) as Record<InsightComponentName, typeof stub>);
const prompt = library.prompt({ additionalRules: PROMPT_RULES, examples: PROMPT_EXAMPLES });

const target = fileURLToPath(new URL("../../backend/src/lib/insights/uiPrompt.generated.ts", import.meta.url));
writeFileSync(
  target,
  `// GENERATED by frontend/scripts/insights-prompt.ts from frontend/app/lib/insights/schema.ts — do not edit.\n` +
    `// OpenUI Lang instructions for the Leadership Insights component library.\n` +
    `export const INSIGHTS_UI_PROMPT = ${JSON.stringify(prompt)};\n`,
);
console.log(`Wrote ${target} (${prompt.length} chars)`);
